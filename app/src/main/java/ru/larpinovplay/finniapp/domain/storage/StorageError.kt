package ru.larpinovplay.finniapp.domain.storage

import ru.larpinovplay.finniapp.domain.util.result.DomainError

/**
 * Что может пойти не так при чтении и записи сохранений. Домен знает только о причине для пользователя;
 * исключения библиотеки хранения (DataStore, Room) остаются в слое `data` и сюда не попадают.
 */
enum class StorageError : DomainError {

    /** Не удалось прочитать файл: диск недоступен или ошибка ввода-вывода. Сохранение цело, можно повторить. */
    READ_FAILED,

    /** Не удалось записать: нет места, диск недоступен. Прежнее сохранение цело, изменение не применено. */
    WRITE_FAILED,

    /** Файл повреждён и не читается. Сохранение сброшено, начинать нужно заново. */
    CORRUPTED,

    /** Сохранение записано другой версией приложения и несовместимо с этой. Оно сброшено, начинать нужно заново. */
    INCOMPATIBLE_VERSION,
}
