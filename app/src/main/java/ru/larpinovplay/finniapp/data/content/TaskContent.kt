private const val LEVEL_REWARD = 3
private const val LEVEL_REWARD_ON_MISTAKE = 2

private fun level(id: String, topic: TaskTopic, title: String, week: Int, vararg tasks: Task) =
    Level(id, topic, title, week, LEVEL_REWARD, LEVEL_REWARD_ON_MISTAKE, tasks.toList())

private fun choice(id: String, intro: String, hint: String, success: String, mistake: String, vararg options: Option) =
    Task(id, intro, success, mistake, hint, TaskPayload.Choice(options.toList()))

private fun right(id: String, text: String, consequence: String) = Option(id, text, correct = true, consequence)

private fun wrong(id: String, text: String, consequence: String) = Option(id, text, correct = false, consequence)

private fun allocate(
    id: String, intro: String, hint: String, success: String, mistake: String,
    total: Int, mandatoryMin: Int, savingsMin: Int,
) = Task(
    id, intro, success, mistake, hint,
    TaskPayload.Allocate(
        total = total, step = 5,
        buckets = listOf(
            TaskPayload.Allocate.Bucket("mandatory", "Обязательное"),
            TaskPayload.Allocate.Bucket("optional", "Необязательное"),
            TaskPayload.Allocate.Bucket("savings", "Копилка"),
        ),
        mandatoryMin = mandatoryMin, savingsMin = savingsMin,
    ),
)

private fun shopList(
    id: String, intro: String, hint: String, success: String, mistake: String,
    budget: Int, vararg items: TaskPayload.ShopList.Item,
) = Task(id, intro, success, mistake, hint, TaskPayload.ShopList(budget, items.toList()))

private fun item(id: String, name: String, price: Int, mandatory: Boolean = false) =
    TaskPayload.ShopList.Item(id, name, price, mandatory)
